const listeners = new Set()
function emit() { listeners.forEach((cb) => cb()) }

function baseLang(code) {
  if (!code || code === 'system') {
    const nav = typeof navigator !== 'undefined' ? (navigator.language || 'en') : 'en'
    return nav.split('-')[0]
  }
  return code.split('-')[0]
}

export function t(key, fallback) {
  const lang = baseLang(pb.authStore.model?.locale)
  return dict[lang]?.[key] || dict.en[key] || fallback || key
}

// Re-renders the caller when the user changes language.
export function useI18n() {
  const [, force] = useState(0)
  useEffect(() => {
    const cb = () => force((n) => n + 1)
    listeners.add(cb)
    const unsub = pb.authStore.onChange(() => emit())
    return () => {
      listeners.delete(cb)
      unsub()
    }
  }, [])
  return { t, locale: pb.authStore.model?.locale || 'system' }
}
